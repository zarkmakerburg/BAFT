#!/usr/bin/env python3
"""Regenerate the BAFT mark that install.sh draws in the terminal.

The mark is stored in install.sh as a small palette and a pixel grid
('.' is transparent), so the terminal background shows through and the
script can draw it in true colour or the 256-colour palette at run time.

    python3 scripts/install-logo.py web/assets/baft-brand.png          # print
    python3 scripts/install-logo.py web/assets/baft-brand.png --write  # update install.sh

Needs Pillow; only maintainers run it, the installer itself does not.
"""
import pathlib, re, sys
from PIL import Image

ROWS, COLORS = 36, 8          # pixel rows (two per terminal line), palette size
ALPHA, LIFT = 110, 44          # opacity cut-off; darkest channel value kept visible


def xterm256(rgb):
    """Closest xterm-256 colour (cube or grey ramp) by the "redmean" distance,
    which keeps gold gold instead of drifting to salmon or olive."""
    steps = [0, 95, 135, 175, 215, 255]
    table = {16 + 36 * r + 6 * g + b: (steps[r], steps[g], steps[b]) for r in range(6) for g in range(6) for b in range(6)}
    table.update({232 + i: (8 + 10 * i,) * 3 for i in range(24)})

    def dist(c):
        rm = (c[0] + rgb[0]) / 2
        dr, dg, db = c[0] - rgb[0], c[1] - rgb[1], c[2] - rgb[2]
        return (2 + rm / 256) * dr * dr + 4 * dg * dg + (2 + (255 - rm) / 256) * db * db

    return min(table, key=lambda n: dist(table[n]))


def build(path):
    im = Image.open(path).convert("RGBA")
    im = im.crop(im.getchannel("A").point(lambda a: 255 if a > ALPHA else 0).getbbox())
    w = max(1, round(im.width * ROWS / im.height))
    im = im.resize((w, ROWS), Image.LANCZOS)
    alpha = im.getchannel("A")
    rgb = Image.new("RGB", im.size)
    rgb.paste(im.convert("RGB").point(lambda v: max(v, LIFT)))
    pal = rgb.quantize(COLORS, method=Image.Quantize.MEDIANCUT)
    colors = pal.getpalette()[: COLORS * 3]
    colors = [tuple(colors[i : i + 3]) for i in range(0, len(colors), 3)]
    rows = []
    for y in range(ROWS):
        rows.append("".join("." if alpha.getpixel((x, y)) <= ALPHA else "abcdefgh"[pal.getpixel((x, y))] for x in range(w)))
    out = ["# >>> logo (generated by scripts/install-logo.py; do not edit by hand)"]
    out.append("LOGO_RGB=(" + " ".join(f"'{r};{g};{b}'" for r, g, b in colors) + ")")
    out.append("LOGO_256=(" + " ".join(str(xterm256(c)) for c in colors) + ")")
    out.append("LOGO_ROWS=(")
    out += [f"  '{r}'" for r in rows]
    out.append(")")
    out.append("# <<< logo")
    return "\n".join(out)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    block = build(sys.argv[1])
    if "--write" not in sys.argv:
        print(block)
        return
    target = pathlib.Path(__file__).resolve().parent.parent / "install.sh"
    text = target.read_text()
    new, n = re.subn(r"# >>> logo.*?# <<< logo", lambda _: block, text, flags=re.S)
    if n != 1:
        sys.exit("install.sh has no single '# >>> logo' block")
    target.write_text(new)


if __name__ == "__main__":
    main()
